"""Write learning/INDEX.md, the index of the learning material, from learning/manifest.json.

python3 learning/build_index.py           # write INDEX.md
python3 learning/build_index.py --check   # exit 1 if INDEX.md is not what the manifest gives
"""

import json
import sys
from pathlib import Path

LEARNING = Path(__file__).resolve().parent
MANIFEST = json.loads((LEARNING / "manifest.json").read_text(encoding="utf-8"))
KINDS = {
    "tutorial": "Tutorials",
    "viewer": "Interactive viewers",
    "sequence": "Illustrated sequences",
    "blog": "Blog material",
    "release": "Offline edition",
}


def files(paths):
    return ", ".join(f"[`{Path(p).name}`]({p})" for p in paths) or "—"


def render():
    b = MANIFEST["branch"]
    rel = MANIFEST["release"]
    out = [
        "# Learning material index",
        "",
        "<!-- Generated by build_index.py from manifest.json; edit the manifest, then rerun. -->",
        "",
        f"Branch: **`{b['name']}`**"
        + (" (locked)" if b.get("locked") else "")
        + f". {b['policy']}"
        + (f" {b['protection']}" if b.get("protection") else "")
        + " See [the lock](README.md#the-lock).",
        "",
        "Each component below lists its entry page, the scripts that generate it, its docs and its checks.",
        "Commands run from the repository root; `$PY` is `$(./scripts/resolve_python_env.sh)`. The browser",
        "tools need Playwright with Chromium (or a `--chrome` binary).",
        "",
        "| Component | Kind | Entry | Origin |",
        "|---|---|---|---|",
    ]
    for c in MANIFEST["components"]:
        out.append(
            f"| [{c['title']}](#{c['id']}) | {c['kind']} | [{Path(c['entry']).name}]({c['entry']}) | {c['origin']} |"
        )
    for kind, heading in KINDS.items():
        comps = [c for c in MANIFEST["components"] if c["kind"] == kind]
        if not comps:
            continue
        out += ["", f"## {heading}"]
        for c in comps:
            out += [
                "",
                f'<a id="{c["id"]}"></a>',
                "",
                f"### {c['title']}",
                "",
                c["summary"],
                "",
                f"- **Folder:** [`{c['path']}/`]({c['path']})",
                f"- **Entry:** [{Path(c['entry']).name}]({c['entry']})",
                f"- **Generators:** {files(c['generators'])}",
                f"- **Docs:** {files(c['docs'])}",
                f"- **Checks:** {files(c['checks'])}",
                f"- **Origin:** {c['origin']}",
            ]
            if c.get("run"):
                out += ["", "```sh", *c["run"], "```"]
    out += [
        "",
        "## Keeping it consistent",
        "",
        "- [`manifest.json`](manifest.json) is the source of this index; `python3 learning/build_index.py` rewrites it.",
        f"- The offline edition (`{rel['output']}/`) covers {', '.join(f'`{f}/`' for f in rel['include'])} and links",
        f"  files it does not copy to GitHub at commit `{rel['source_ref'][:8]}`.",
        "- `python3 learning/check_manifest.py` checks the branch lock, every listed file, the links in every doc,",
        "  that this index is current, and that the offline edition matches its sources.",
        "- [`SECURITY.md`](SECURITY.md) records the security review of this material and how to repeat it.",
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    target = LEARNING / MANIFEST.get("index", "INDEX.md")
    if "--check" in sys.argv[1:]:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        raise SystemExit(0 if current == text else 1)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target.relative_to(LEARNING.parent)}")
